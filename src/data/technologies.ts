export function getTechnologyById(id: string): Technology | undefined {
  const normalized = id.toLowerCase().trim();
  return technologies.find(
    (t) =>
      t.id === normalized ||
      t.name.toLowerCase() === normalized ||
      t.aliases?.some((a) => a.toLowerCase() === normalized)
  );
}

export function getTechnologiesByCategory(category: TechnologyCategory): Technology[] {
  return technologies.filter((t) => t.categories.includes(category));
}

export function getTechnologiesForProject(projectSlug: string): Technology[] {
  return technologies.filter((t) => t.projectSlugs.includes(projectSlug));
}

export function getCoreTechnologies(): Technology[] {
  return technologies.filter((t) => t.status === 'core');
}
